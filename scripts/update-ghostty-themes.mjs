#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

// This is the exact audited theme dependency pinned by Ghostty's build.zig.zon at the recorded commit.
// Updating the catalog is deliberate: first update these three values from official Ghostty source, then run
// this script. The checksum makes a changed archive fail closed instead of silently changing release bytes.
const GHOSTTY_COMMIT = "c54ec80c55a045312f7c97d66b32c8043526f03c";
const SOURCE_DATE = "2026-08-03";
const ARCHIVE_URL = "https://deps.files.ghostty.org/ghostty-themes-release-20260803-155300-875a82f.tgz";
const ARCHIVE_SHA256 = "feac4b6bd4bc6d28363406c9cf012d6611af3b168f4c05453569c10acfcc141b";
const OUTPUT = resolve("packages/web/src/appearance/ghostty-themes.generated.ts");

function value(contents, key, fallback) {
  const match = new RegExp(`^${key}\\s*=\\s*(#[0-9a-fA-F]{6})$`, "m").exec(contents);
  return (match?.[1] ?? fallback).toLowerCase();
}

function parseTheme(name, contents) {
  const palette = Array.from({ length: 16 });
  for (const match of contents.matchAll(/^palette\s*=\s*(\d+)=(#[0-9a-fA-F]{6})$/gm)) {
    const index = Number(match[1]);
    if (index >= 0 && index < 16) palette[index] = match[2].toLowerCase();
  }
  if (palette.some((color) => color === undefined)) throw new Error(`incomplete palette: ${name}`);
  const background = value(contents, "background", "#000000");
  const foreground = value(contents, "foreground", "#ffffff");
  return {
    name,
    background,
    foreground,
    cursor: value(contents, "cursor-color", foreground),
    cursorText: value(contents, "cursor-text", background),
    selectionBackground: value(contents, "selection-background", palette[8]),
    selectionForeground: value(contents, "selection-foreground", foreground),
    palette,
  };
}

function moduleSource(themes) {
  const rows = themes.map((theme) => `  ${JSON.stringify(theme)},`).join("\n");
  return `/**
 * GENERATED by scripts/update-ghostty-themes.mjs — do not hand-edit.
 * Official Ghostty commit: ${GHOSTTY_COMMIT}
 * Official pinned theme archive: ${ARCHIVE_URL}
 * Archive SHA-256: ${ARCHIVE_SHA256}
 */
export interface GhosttyThemeDefinition {
  readonly name: string;
  readonly background: string;
  readonly foreground: string;
  readonly cursor: string;
  readonly cursorText: string;
  readonly selectionBackground: string;
  readonly selectionForeground: string;
  readonly palette: readonly string[];
}

export const GHOSTTY_THEME_SOURCE = {
  ghosttyCommit: "${GHOSTTY_COMMIT}",
  sourceDate: "${SOURCE_DATE}",
  archiveSha256: "${ARCHIVE_SHA256}",
} as const;

// prettier-ignore
export const GHOSTTY_THEMES: readonly GhosttyThemeDefinition[] = [
${rows}
];

export const GHOSTTY_THEME_BY_NAME = new Map(GHOSTTY_THEMES.map((theme) => [theme.name, theme]));
`;
}

const scratch = await mkdtemp(join(tmpdir(), "roamcode-ghostty-themes-"));
try {
  const archive = join(scratch, "themes.tgz");
  const response = await fetch(ARCHIVE_URL);
  if (!response.ok) throw new Error(`theme download failed (${response.status})`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== ARCHIVE_SHA256) throw new Error(`theme archive checksum mismatch: ${digest}`);
  await writeFile(archive, bytes);
  const tar = spawnSync("tar", ["-xzf", archive, "-C", scratch], { encoding: "utf8" });
  if (tar.status !== 0) throw new Error(tar.stderr || "could not extract theme archive");
  const themeDir = join(scratch, "ghostty");
  const names = (await readdir(themeDir)).sort((left, right) => left.localeCompare(right, "en"));
  const themes = [];
  for (const name of names) themes.push(parseTheme(name, await readFile(join(themeDir, name), "utf8")));
  if (themes.length !== 602) throw new Error(`expected 602 Ghostty themes, received ${themes.length}`);
  await writeFile(OUTPUT, moduleSource(themes));
  process.stdout.write(`Updated ${themes.length} Ghostty themes at ${OUTPUT}\n`);
} finally {
  await rm(scratch, { recursive: true, force: true });
}
